import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';
const sql=file=>readFileSync(new URL('../'+file,import.meta.url),'utf8');
const child='10000000-0000-4000-8000-000000000001',other='10000000-0000-4000-8000-000000000002',parent='10000000-0000-4000-8000-000000000003';
test('PostgreSQL: migrace, RLS, atomický zápis, opakování a rodičovský přístup',async()=>{
 const db=new PGlite();
 try{
 await db.exec(`create role anon; create role authenticated; create schema auth;
 create table auth.users(id uuid primary key,email text,raw_user_meta_data jsonb);
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 grant usage on schema public,auth to authenticated;
 grant execute on function auth.uid() to authenticated;`);
 await db.exec(sql('schema.sql'));await db.exec(sql('migrations/001_question_difficulty.sql'));
 await db.exec(sql('migrations/002_app_support.sql'));await db.exec(sql('migrations/002_app_support.sql'));
 await db.exec(sql('migrations/003_starter_questions.sql'));await db.exec(sql('migrations/003_starter_questions.sql'));
 const bank=await db.query("select topic,difficulty,count(*)::int as n from questions where topic not in ('mechanika','elektrina') group by topic,difficulty");assert.equal(bank.rows.length,24);assert(bank.rows.every(r=>r.n===4));
 await assert.rejects(db.exec("update questions set difficulty = 'jina'"));await assert.rejects(db.exec('update questions set difficulty = null'));
 await db.exec(`insert into auth.users values ('${child}','child@test.invalid','{"display_name":"Dítě"}'),('${other}','other@test.invalid','{}'),('${parent}','parent@test.invalid','{}');
 grant select,insert,update,delete on public.questions,public.profiles,public.attempts,public.answers to authenticated;
 insert into parent_access values ('${parent}','${child}');`);
 const login=async id=>{await db.exec('reset role');await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]);await db.exec('set role authenticated');};
 await login(child);
 assert.equal((await db.query('select * from profiles')).rows.length,1);
 await assert.rejects(db.exec(`insert into parent_access values ('${child}','${other}')`));
 await assert.rejects(db.exec("insert into questions(topic,question,correct_answer,wrong_answer_1,wrong_answer_2,wrong_answer_3) values ('si','x','a','b','c','d')"));
 const qs=(await db.query("select * from questions where topic='si' and difficulty='zakladni' order by id")).rows;
 const payload=qs.map(q=>({question_id:q.id,chosen_answer:q.correct_answer}));
 const attempt='20000000-0000-4000-8000-000000000001';
 const save=(id,answers=payload)=>db.query('select save_attempt($1,$2,$3::jsonb)',[id,'si',JSON.stringify(answers)]);
 await save(attempt);await save(attempt);
 assert.equal((await db.query('select * from attempts')).rows.length,1);assert.equal((await db.query('select * from answers')).rows.length,4);
 assert.equal((await db.query('select score from attempts')).rows[0].score,4);
 assert.ok((await db.query('select snapshot from answers limit 1')).rows[0].snapshot.question);
 const invalid=[...payload.slice(0,3),{...payload[3],chosen_answer:'neexistuje'}];
 await assert.rejects(save('20000000-0000-4000-8000-000000000002',invalid));
 assert.equal((await db.query('select * from attempts')).rows.length,1);
 await assert.rejects(save('20000000-0000-4000-8000-000000000003',Array(4).fill(payload[0])));
 await login(other);assert.equal((await db.query('select * from attempts')).rows.length,0);assert.equal((await db.query('select * from answers')).rows.length,0);
 await assert.rejects(db.query('insert into answers(attempt_id,question_id,user_id,chosen_answer,is_correct) values ($1,$2,$3,$4,true)',[attempt,qs[0].id,other,qs[0].correct_answer]));
 await login(parent);assert.equal((await db.query('select * from attempts')).rows.length,1);assert.equal((await db.query('select * from answers')).rows.length,4);assert.equal((await db.query('select * from profiles')).rows.length,2);
 await db.exec('update attempts set score=0');assert.equal((await db.query('select score from attempts')).rows[0].score,4);
 await db.exec("update profiles set display_name='Cizí změna' where id='"+child+"'");assert.equal((await db.query('select display_name from profiles where id=$1',[child])).rows[0].display_name,'Dítě');
 await assert.rejects(save(attempt));
 await db.exec('reset role');await db.exec("alter table questions alter column difficulty drop not null; update questions set difficulty=null where id='"+qs[0].id+"'");
 await assert.rejects(db.exec(sql('migrations/001_question_difficulty.sql')));await db.exec('rollback');assert.equal((await db.query('select difficulty from questions where id=$1',[qs[0].id])).rows[0].difficulty,null);
 }finally{await db.close();}
});
